// Browser-only GitHub publishing. Never persist credentials or include them in URLs.
export const GOVERNANCE_REPO = 'robin-bajaj/cdo-semantic-governance'
export function registryFilename(contract) {
  if (!/^[a-z][a-z0-9_.]*$/.test(contract.name) || !Number.isSafeInteger(Number(contract.version)) || Number(contract.version) < 1) {
    throw Error('Invalid contract name or version')
  }
  return `contracts/${contract.name.replaceAll('.', '_')}_v${contract.version}.yml`
}
function base64Utf8(value) {
  const bytes = new TextEncoder().encode(value)
  let binary = ''
  for (const byte of bytes) binary += String.fromCharCode(byte)
  return btoa(binary)
}
export async function publishContractPR({ contract, yamlText, token, fetchImpl = fetch }) {
  if (!token?.trim()) throw Error('Enter a GitHub fine-grained access token first.')
  const api = 'https://api.github.com'
  const headers = {
    Authorization: `Bearer ${token.trim()}`,
    Accept: 'application/vnd.github+json',
    'X-GitHub-Api-Version': '2022-11-28',
  }
  async function request(path, options = {}) {
    const response = await fetchImpl(`${api}${path}`, {
      ...options, headers: { ...headers, ...(options.body ? { 'Content-Type': 'application/json' } : {}) },
    })
    const payload = await response.json().catch(() => ({}))
    if (!response.ok) throw Error(`GitHub ${response.status}: ${payload.message || 'Request failed'}`)
    return payload
  }
  const path = registryFilename(contract)
  const base = await request(`/repos/${GOVERNANCE_REPO}/git/ref/heads/main`)
  const existingResponse = await fetchImpl(`${api}/repos/${GOVERNANCE_REPO}/contents/${path}?ref=main`, { headers })
  if (existingResponse.status !== 404) {
    if (!existingResponse.ok) {
      const failure = await existingResponse.json().catch(() => ({}))
      throw Error(`GitHub ${existingResponse.status}: ${failure.message || 'Cannot check existing version'}`)
    }
    throw Error(`${path} already exists on main. Create a new version instead of overwriting a released contract.`)
  }
  const branch = `contract-designer/${contract.name.replaceAll('.', '-')}-v${contract.version}-${Date.now().toString(36)}`
  await request(`/repos/${GOVERNANCE_REPO}/git/refs`, {
    method: 'POST', body: JSON.stringify({ ref: `refs/heads/${branch}`, sha: base.object.sha }),
  })
  await request(`/repos/${GOVERNANCE_REPO}/contents/${path}`, {
    method: 'PUT',
    body: JSON.stringify({
      message: `feat(contracts): propose ${contract.name} v${contract.version}`,
      content: base64Utf8(yamlText),
      branch,
    }),
  })
  const pr = await request(`/repos/${GOVERNANCE_REPO}/pulls`, {
    method: 'POST',
    body: JSON.stringify({
      title: `Contract: ${contract.name} v${contract.version}`,
      head: branch, base: 'main',
      body: `Generated by Contract Designer.\n\nContract: \`${contract.name}\` v${contract.version}\nPath: \`${path}\`\n\nPlease review the contract and run the CDO registry validation/CI before merging. The visual editor performs only local structural checks.`,
    }),
  })
  return { url: pr.html_url, number: pr.number, path, branch }
}
